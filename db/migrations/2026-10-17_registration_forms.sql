-- Conference form v2 (photo, payer name, Student / Other category, dietary)
-- and Hackathon Round 1 registration.
-- Additive and re-runnable. Rollback: 2026-10-17_registration_forms.down.sql

BEGIN;

-- Conference -------------------------------------------------------------

ALTER TABLE category ADD COLUMN IF NOT EXISTS sort_order integer DEFAULT 0 NOT NULL;

INSERT INTO category (name)
SELECT 'Student'
WHERE NOT EXISTS (SELECT 1 FROM category WHERE name = 'Student');

UPDATE category SET sort_order = CASE name
  WHEN 'Healthcare professional' THEN 1
  WHEN 'Faculty / Academician' THEN 2
  WHEN 'Researcher' THEN 3
  WHEN 'Industry professional' THEN 4
  WHEN 'Student' THEN 5
  WHEN 'International delegate' THEN 6
  WHEN 'Other' THEN 7
  ELSE sort_order
END;

ALTER TABLE registration
  ADD COLUMN IF NOT EXISTS attendee_photo_path text,
  ADD COLUMN IF NOT EXISTS category_other character varying(150),
  ADD COLUMN IF NOT EXISTS dietary_preference character varying(30);

ALTER TABLE registration_payment
  ADD COLUMN IF NOT EXISTS payer_name character varying(200);

-- Hackathon --------------------------------------------------------------

CREATE TABLE IF NOT EXISTS hackathon_discipline (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name character varying(150) NOT NULL,
    created_at timestamp without time zone DEFAULT LOCALTIMESTAMP NOT NULL,
    status smallint DEFAULT 1 NOT NULL,
    CONSTRAINT hackathon_discipline_status_check CHECK ((status = ANY (ARRAY[0, 1])))
);

CREATE TABLE IF NOT EXISTS hackathon_declaration (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name character varying(500) NOT NULL,
    kind character varying(20) NOT NULL,
    created_at timestamp without time zone DEFAULT LOCALTIMESTAMP NOT NULL,
    status smallint DEFAULT 1 NOT NULL,
    CONSTRAINT hackathon_declaration_kind_check CHECK (((kind)::text = ANY (ARRAY['commitment', 'consent']))),
    CONSTRAINT hackathon_declaration_status_check CHECK ((status = ANY (ARRAY[0, 1])))
);

CREATE SEQUENCE IF NOT EXISTS hackathon_code_seq START WITH 1 INCREMENT BY 1;

-- status: 1 submitted, 2 under review, 3 shortlisted, 0 rejected
CREATE TABLE IF NOT EXISTS hackathon_registration (
    id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
    registration_code character varying(20) DEFAULT lpad((nextval('hackathon_code_seq'::regclass))::text, 2, '0'::text),
    full_name character varying(200) NOT NULL,
    date_of_birth date NOT NULL,
    gender character varying(30) NOT NULL,
    email_address character varying(255) NOT NULL,
    mobile_number character varying(30) NOT NULL,
    city_district character varying(100) NOT NULL,
    state_ut character varying(100) NOT NULL,
    institution_name character varying(255) NOT NULL,
    course_programme character varying(255) NOT NULL,
    specialisation character varying(255) NOT NULL,
    year_of_study character varying(50) NOT NULL,
    discipline integer NOT NULL REFERENCES hackathon_discipline(id),
    discipline_other character varying(150),
    institution_id_path text NOT NULL,
    solution_path text NOT NULL,
    declaration text NOT NULL,
    created_at timestamp without time zone DEFAULT LOCALTIMESTAMP NOT NULL,
    status smallint DEFAULT 1 NOT NULL,
    CONSTRAINT hackathon_registration_status_check CHECK ((status = ANY (ARRAY[0, 1, 2, 3])))
);

CREATE UNIQUE INDEX IF NOT EXISTS hackathon_registration_email_key
  ON hackathon_registration (lower((email_address)::text));
CREATE UNIQUE INDEX IF NOT EXISTS hackathon_registration_code_key
  ON hackathon_registration (registration_code);

INSERT INTO hackathon_discipline (name)
SELECT v.name
FROM (VALUES
  (1, 'Healthcare'),
  (2, 'Medicine'),
  (3, 'Engineering'),
  (4, 'AI / Data Science'),
  (5, 'Computer Science / IT'),
  (6, 'Others')
) AS v(ord, name)
WHERE NOT EXISTS (SELECT 1 FROM hackathon_discipline d WHERE d.name = v.name)
ORDER BY v.ord;

INSERT INTO hackathon_declaration (name, kind)
SELECT v.name, v.kind
FROM (VALUES
  (1, 'I am registering individually.', 'commitment'),
  (2, 'I am willing to work in a cross-disciplinary team if selected.', 'commitment'),
  (3, 'I am willing to attend the on-campus Grand Finale if shortlisted.', 'commitment'),
  (4, 'I confirm that all information submitted is accurate.', 'consent'),
  (5, 'I agree to the Hackathon Terms & Conditions.', 'consent'),
  (6, 'I consent to the use of my registration information for programme administration and official communication.', 'consent')
) AS v(ord, name, kind)
WHERE NOT EXISTS (SELECT 1 FROM hackathon_declaration d WHERE d.name = v.name)
ORDER BY v.ord;

COMMIT;
